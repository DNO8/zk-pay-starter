import { existsSync } from "node:fs";

function unquote(v: string): string {
  const t = v.trim();
  if (
    (t.startsWith('"') && t.endsWith('"') && t.length >= 2) ||
    (t.startsWith("'") && t.endsWith("'") && t.length >= 2)
  ) {
    return t.slice(1, -1);
  }
  return t;
}

function quoteEnvValue(v: string): string {
  if (v === "" || /[\s#"'$`\\]/.test(v)) {
    return `"${v.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
  }
  return v;
}

export async function readEnvFile(path = ".env"): Promise<Record<string, string>> {
  if (!existsSync(path)) return {};
  const text = await Bun.file(path).text();
  const out: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const eq = t.indexOf("=");
    if (eq < 0) continue;
    out[t.slice(0, eq)] = unquote(t.slice(eq + 1));
  }
  return out;
}

export function getEnv(env: Record<string, string>, key: string, fallback = ""): string {
  return env[key] ?? process.env[key] ?? fallback;
}

export async function writeEnv(values: Record<string, string>, path = ".env"): Promise<void> {
  const existing = await readEnvFile(path);
  const merged = { ...existing, ...values };
  const lines = [
    "# Auto-generated by zk-pay-starter scripts. Contains secrets — never commit.",
    "# Regenerated by `bun run setup` / `bun run deploy`.",
    "",
  ];
  for (const [k, v] of Object.entries(merged)) {
    if (k.startsWith("#")) continue;
    lines.push(`${k}=${quoteEnvValue(v)}`);
  }
  await Bun.write(path, lines.join("\n") + "\n");
}
